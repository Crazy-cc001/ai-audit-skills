# -*- coding: utf-8 -*-
"""差异说明写入对应审定表的审计说明区"""
import openpyxl

TPL = r'C:\path\to\底稿模板.xlsx'
wb = openpyxl.load_workbook(TPL)

def find_note_row(ws, start, rmax):
    for r in range(start, rmax):
        v = ws.cell(row=r, column=2).value
        if v and ('经核对' in str(v) or '相符' in str(v)):
            return r
    return None

# ---- 业务活动成本审定表 ----
ws = wb['业务活动成本审定表']
r = find_note_row(ws, 109, 130)
if r:
    ws.cell(row=r, column=2, value=
        '经核对报表、总账、明细账金额相符。账表差异（账套借方累计 vs 报表本年数）：'
        '2019年+720.00元（报表多，涉及多笔"加班费"720元及红字调整分录口径差异）、'
        '2020年-6,940.00元（账套多，含12-31记-28"收到上级协会减免会费"冲减33,762.00元等调整分录净影响）、'
        '2021年-3,080.00元、2022年-15,900.00元、2023年-13,725.80元、2024年-3,600.00元；'
        '可能原因：账套红字冲减及跨期调整分录与报表编制口径不一致，建议结合各年调整分录逐笔核实。')

# ---- 管理费用审定表 ----
ws = wb['管理费用审定表']
r = find_note_row(ws, 36, 60)
if r:
    ws.cell(row=r, column=2, value=
        '经核对报表、总账、明细账金额相符。账表差异（账套借方累计 vs 报表本年数）：'
        '2017年-7,307.00元（账套多，恰为一个月员工公积金金额，2017年7-12月每月7,307.00元，'
        '可能系报表漏计一个月公积金）、2021年-13,894.44元、2022年-23,712.00元、2024年-3,790.41元；'
        '可能原因：账套红字冲减及调整分录与报表编制口径不一致，建议逐笔核实。')

wb.save(TPL)
print('差异说明已写入业务活动成本/管理费用审定表')
